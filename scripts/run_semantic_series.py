"""Resumable ordered experiment, with bounded retries only for invalid contracts.

Valid wrong answers are never regenerated by this recovery path.
"""
import sys,hashlib
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1];sys.path.insert(0,str(ROOT))
from src.config import atomic_json
from scripts import semantic_fallback as base
from scripts import semantic_fallback_augmentation as augmented
from scripts import context_utility as generator

def repair_invalid(out):
    for path in sorted((out/'qa').glob('*.json')):
        r=base.read(path)
        if r.get('evaluation_status') not in ['invalid_contract','invalid_judge']:continue
        for attempt in range(2):
            bad=base.read(path);digest=hashlib.sha256(path.read_bytes()).hexdigest()
            archive=out/'invalid_attempts'/f'{path.stem}-{digest[:12]}.json';atomic_json(archive,bad)
            retry=out/'repairs'/f'{path.stem}-{digest[:12]}';task=next(t for t in base.read(out/'tasks.json') if t['question_id']==bad['question_id'] and t['method']==bad['method'])
            atomic_json(retry/'protocol.json',dict(reason='Retry invalid output only; same prompt/model/budget; never resample a valid wrong answer',original_record_sha256=digest,attempt=attempt))
            atomic_json(retry/'tasks.json',[task])
            if bad['evaluation_status']=='invalid_judge':atomic_json(retry/'qa'/path.name,dict(task,generation=bad['generation']))
            previous=generator.OUT
            try:generator.OUT=retry;generator.qa('all')
            finally:generator.OUT=previous
            fixed=base.read(retry/'qa'/path.name);fixed['repair_attempts']=bad.get('repair_attempts',[])+([bad['generation']] if bad['evaluation_status']=='invalid_contract' else [])
            fixed['repair_judges']=bad.get('repair_judges',[])+([bad['judge_response']] if 'judge_response' in bad else [])
            fixed['repair_reason']='Invalid contract/grade only; originals archived; no semantic relabeling.';atomic_json(path,fixed)
            if fixed['evaluation_status'] in ['graded','explicit_abstention']:break
        else:raise RuntimeError('Invalid output persisted after two retries; records preserved')

if __name__=='__main__':
    base.prepare();base.qa('development');repair_invalid(base.OUT)
    augmented.prepare();augmented.qa();repair_invalid(augmented.OUT)
    base.train();augmented.train();base.qa('test');repair_invalid(base.OUT)
    print('All factual answers and both frozen model recipes ready for analysis.')
